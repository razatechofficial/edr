// TestLinuxMonitoringCategories proves one capability category per subtest.
//
// All subtests share one driver. Loading and attaching sixty-one programs
// takes seconds, and a per-subtest driver would also mean a per-subtest ring
// buffer that nobody drains while the previous subtest runs. Each subtest
// takes a cursor into the shared event tap before generating its activity, so
// one subtest's events cannot satisfy another's assertion.
func TestLinuxMonitoringCategories(t *testing.T) {
	drv, tap := startMonitoringForTest(t)

	proofs := linuxCategoryProofs()

	// A new canonical category must get a case here or this fails. That is
	// the point of the list: "we cover every category" is a claim that
	// rots silently otherwise.
	covered := make(map[CapabilityCategory]bool, len(proofs))
	for _, pr := range proofs {
		if covered[pr.cat] {
			t.Errorf("category %q has more than one proof case", pr.cat)
		}
		covered[pr.cat] = true
	}
	for _, cat := range CanonicalCapabilityCategories {
		if !covered[cat] {
			t.Errorf("capability category %q has no proof case in linuxCategoryProofs; add one, or add it with an unsupported reason if Linux genuinely cannot serve it", cat)
		}
	}

	for _, pr := range proofs {
		pr := pr
		t.Run(string(pr.cat), func(t *testing.T) {
			rep := drv.CapabilityReport()
			c := findCapability(t, rep, pr.cat)

			if pr.unsupported != "" {
				if c.Present {
					t.Fatalf("category %q is marked unsupported on Linux here but the capability report says present=true with mechanism %q; one of the two is wrong", pr.cat, c.Mechanism)
				}
				if c.Reason == "" {
					t.Errorf("category %q is absent with no reason; the console shows this row and needs to say why", pr.cat)
				}
				t.Skipf("NOT SUPPORTED ON THIS OS: %s", pr.unsupported)
			}

			requireCategory(t, drv, pr.cat)

			p := &linuxProof{drv: drv, tap: tap, dir: t.TempDir()}
			pr.prove(t, p)

			// The capability report must agree with the ring
			// buffer: it is the data the console shows, so it has
			// to reflect the same reality.
			if c := findCapability(t, drv.CapabilityReport(), pr.cat); !c.Producing {
				t.Errorf("an event for %q was observed on the ring buffer but CapabilityReport says it is not producing: %+v", pr.cat, c)
			}
		})
	}

	t.Logf("final capability summary on this kernel: %+v", drv.CapabilityReport().Summary)
}

// TestLinuxMonitoringCapabilityReportMatchesAttachments asserts the report an
// operator would read agrees with what the driver actually attached, on a real
// kernel. The static tests check the tables; this checks the live wiring.
func TestLinuxMonitoringCapabilityReportMatchesAttachments(t *testing.T) {
	drv, _ := startMonitoringForTest(t)

	attached := make(map[string]bool)
	for _, p := range drv.AttachedProgramNames() {
		attached[p] = true
	}

	rep := drv.CapabilityReport()
	if !rep.DriverRunning {
		t.Fatal("report says driver_running=false for a driver that started")
	}

	for _, c := range rep.Categories {
		for _, hook := range c.Attachments {
			if c.Attached && !attached[hook] {
				t.Errorf("category %q reports attachment %q, which is not in the driver's attach records", c.Category, hook)
			}
		}
		if c.Attached && len(c.Attachments) == 0 {
			t.Errorf("category %q is attached but names no attachment", c.Category)
		}
		if !c.Present && c.Reason == "" {
			t.Errorf("category %q is absent with no reason", c.Category)
		}
	}

	// The LSM enforcement hooks are the only programs the loader
	// deliberately never attaches, and signal is the only category whose
	// every hook is one of them. It must read dark on a real kernel.
	if c := findCapability(t, rep, CapSignal); c.Attached {
		t.Errorf("category signal reports attached, but its only hook is lsm_task_kill, which the loader does not attach: %+v", c)
	}

	// registry_write is the one category with no Linux mechanism at all.
	if c := findCapability(t, rep, CapRegistryWrite); c.Present {
		t.Errorf("category registry_write reports present on Linux: %+v", c)
	}

	t.Logf("capability summary on this kernel: %+v", rep.Summary)
}
