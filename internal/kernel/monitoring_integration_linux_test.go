// resolveBPFObjectForTest finds a compiled BPF object, preferring an explicit
// override so CI can point at the object make ebpf-link just produced.
func resolveBPFObjectForTest() (path string, tried []string) {
	if p := strings.TrimSpace(os.Getenv("EDR_BPF_OBJECT")); p != "" {
		tried = append(tried, p+" (from EDR_BPF_OBJECT)")
		if fileExists(p) {
			return p, tried
		}
	}
	candidates := []string{
		bpfObjectPathDefault,
		filepath.Join(EBPFSourceDir(), "edr.bpf.o"),
	}
	for _, p := range candidates {
		tried = append(tried, p)
		if fileExists(p) {
			return p, tried
		}
	}
	return "", tried
}

// ebpfRequired reports whether a load or attach failure must fail the test
// rather than skip it.
//
// CI sets EDR_REQUIRE_EBPF=1. Without it a verifier rejection reads as
// "MISSING PREREQUISITE" and the whole lane goes green having proved nothing,
// which is what happened to this suite: every subtest skipped on
// "eBPF driver failed to start" while capture_argv and tp_dns_sendto were
// being rejected by the verifier, and nobody looked at the log because the
// job was green.
func ebpfRequired() bool {
	switch strings.ToLower(strings.TrimSpace(os.Getenv("EDR_REQUIRE_EBPF"))) {
	case "1", "true", "yes":
		return true
	}
	return false
}

// startMonitoringForTest applies every environment gate in turn and returns a
// started driver plus a tap on its ring buffer.
func startMonitoringForTest(t *testing.T) (*EBPFDriver, *eventTap) {
	t.Helper()
	return startMonitoringForTestWithPolicy(t, nil)
}

// startMonitoringForTestWithPolicy is startMonitoringForTest with a chance to
// change the policy before Start.
//
// It exists because some flags decide what gets attached, not just what gets
// forwarded: with monitoring.sched_events false the scheduler tracepoints are
// not attached at all, so a subtest that wants to prove them needs a driver
// started with the flag on rather than a flag flipped afterwards.
func startMonitoringForTestWithPolicy(t *testing.T, mutate func(*EventPolicy)) (*EBPFDriver, *eventTap) {
	t.Helper()

	if euid := os.Geteuid(); euid != 0 {
		t.Skipf("MISSING PREREQUISITE: root. eBPF program loading needs CAP_BPF and CAP_PERFMON; this process has euid=%d. Re-run with: sudo -E go test -tags=integration ./internal/kernel/ -run %s", euid, t.Name())
	}

	objPath, tried := resolveBPFObjectForTest()
	if objPath == "" && len(bpfBytecode) == 0 {
		t.Skipf("MISSING PREREQUISITE: compiled BPF object. Tried: %s. Build one with `make ebpf ebpf-link`, then set EDR_BPF_OBJECT to platform/linux/ebpf/edr.bpf.o, or build the test with -tags embed_ebpf", strings.Join(tried, ", "))
	}

	if !fileExists("/sys/kernel/btf/vmlinux") {
		t.Skip("MISSING PREREQUISITE: kernel BTF at /sys/kernel/btf/vmlinux. The programs are CO-RE and need BTF; this kernel was built without CONFIG_DEBUG_INFO_BTF")
	}

	drv, err := NewEBPFDriver("monitoring-integration-test", objPath)
	if err != nil {
		t.Skipf("MISSING PREREQUISITE: eBPF driver could not be constructed: %v", err)
	}

	// Per-program run counts, on for the whole suite. They answer the one
	// question a silent category otherwise cannot: a hook the kernel has
	// invoked zero times is a dead link, and a hook it has invoked
	// thousands of times whose events do not arrive is a loss further
	// down. The suite spent several runs unable to tell those apart. The
	// counters cost two timestamp reads per program invocation, which is
	// why they are opt-in in production and unconditional here.
	if err := drv.EnableProgramRunStats(); err != nil {
		t.Logf("per-program run counts unavailable on this kernel: %v", err)
	}

	// LSM-FIM events are off in DefaultPolicy; they are low volume and
	// several file categories can be served by them, so turn them on for
	// the whole run. Scheduler events stay off: with them on, the three
	// sched tracepoints attach and submit on every context switch, which
	// was about 250,000 records a second on this runner and starved every
	// other category. TestLinuxMonitoringScheduler proves that category on
	// a driver of its own.
	pol := DefaultPolicy()
	pol.LSMFimEvents = true
	if mutate != nil {
		mutate(&pol)
	}
	if err := drv.SetPolicy(pol); err != nil {
		t.Fatalf("SetPolicy: %v", err)
	}

	buf := NewRingBuffer(64 << 20)
	ctx, cancel := context.WithCancel(context.Background())

	if err := drv.Start(ctx, buf); err != nil {
		cancel()
		buf.Close()
		msg := fmt.Sprintf("eBPF driver failed to start on this kernel: %v\nLoader diagnostic: %s\nobject=%s", err, drv.LastLoadDiagnostics(), objPath)
		if ebpfRequired() {
			t.Fatalf("EDR_REQUIRE_EBPF=1 and the driver did not start. This is not an environment limitation: the object was built from this tree and the kernel refused it.\n%s", msg)
		}
		t.Skipf("MISSING PREREQUISITE: %s\nSet EDR_REQUIRE_EBPF=1 to make this a failure instead of a skip.", msg)
	}

	t.Cleanup(func() {
		_ = drv.Stop()
		cancel()
		buf.Close()
	})

	attached := drv.AttachedProgramNames()
	if len(attached) == 0 {
		t.Fatalf("driver started but attached no programs; object=%s diagnostic=%s", objPath, drv.LastLoadDiagnostics())
	}
	misses := drv.attachMissReasons()
	t.Logf("driver started on kernel %s: %d of %d programs attached, %d attach misses",
		kernelRelease(), len(attached), len(attached)+len(misses), len(misses))
	for prog, why := range misses {
		t.Logf("  attach miss: %s: %s", prog, why)
	}

	tap := newEventTap(t, buf)
	return drv, tap
}

// requireCategory skips when the capability report says this build or this
// kernel cannot serve the category, quoting the report's own reason — which is
// the kernel's error when the loader recorded one.
func requireCategory(t *testing.T, drv *EBPFDriver, cat CapabilityCategory) {
	t.Helper()
	c := findCapability(t, drv.CapabilityReport(), cat)
	if !c.Present {
		t.Skipf("MISSING PREREQUISITE: no eBPF program in this build serves %q: %s", cat, c.Reason)
	}
	if !c.Attached {
		t.Skipf("MISSING PREREQUISITE: every program serving %q failed to attach on this kernel: %s (candidates: %s)",
			cat, c.Reason, strings.Join(c.Attachments, ", "))
	}
}

