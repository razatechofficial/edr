// linuxEvent is one record off the ring buffer, in whichever of the two
// shapes the driver emits.
//
// writeRawEvent produces a binary frame (type u16 @0, timestamp u64 @2,
// pid u32 @10, tid @14, uid @18, gid @22, payload from rawHeaderSize) for
// process, file and network events. Everything else -- DNS, security,
// privilege, namespace, madvise, sched, TLS -- goes out as a JSON envelope.
// The two are told apart by the first byte: a raw frame's is a small event
// type, a JSON envelope's is '{'.
type linuxEvent struct {
	RawType  uint16
	JSONType string
	Op       string
	PID      uint32
	Str      string
	Raw      []byte
}

func (e linuxEvent) String() string {
	if e.JSONType != "" {
		return fmt.Sprintf("json{type=%s op=%s pid=%d}", e.JSONType, e.Op, e.PID)
	}
	return fmt.Sprintf("raw{type=%d pid=%d str=%q}", e.RawType, e.PID, e.Str)
}

func decodeLinuxEvent(data []byte) (linuxEvent, bool) {
	if len(data) == 0 {
		return linuxEvent{}, false
	}
	if data[0] == '{' {
		var env struct {
			Type      string      `json:"type"`
			Operation string      `json:"operation"`
			EventKind string      `json:"event_kind"`
			PID       uint32      `json:"pid"`
			Query     string      `json:"query"`
			Path      string      `json:"path"`
			Extra     interface{} `json:"-"`
		}
		if json.Unmarshal(data, &env) != nil {
			return linuxEvent{}, false
		}
		op := env.Operation
		if op == "" {
			op = env.EventKind
		}
		str := env.Query
		if str == "" {
			str = env.Path
		}
		return linuxEvent{JSONType: env.Type, Op: op, PID: env.PID, Str: str, Raw: data}, true
	}
	if len(data) < rawHeaderSize {
		return linuxEvent{}, false
	}
	e := linuxEvent{
		RawType: binary.LittleEndian.Uint16(data[0:2]),
		PID:     binary.LittleEndian.Uint32(data[10:14]),
		Raw:     data,
	}
	// The first length-prefixed string of a raw payload: the filename for
	// file events, the exec filename for process events. appendUint32 puts
	// four bytes of PPID first on process events, so both offsets are
	// tried and the one that yields printable text wins.
	payload := data[rawHeaderSize:]
	e.Str = firstPrefixedString(payload)
	if e.Str == "" && len(payload) > 4 {
		e.Str = firstPrefixedString(payload[4:])
	}
	return e, true
}

func firstPrefixedString(payload []byte) string {
	if len(payload) < 2 {
		return ""
	}
	n := int(binary.LittleEndian.Uint16(payload[0:2]))
	if n <= 0 || 2+n > len(payload) {
		return ""
	}
	return string(payload[2 : 2+n])
}

// eventTap drains the ring buffer continuously into a bounded log.
//
// A single draining reader shared by every subtest is deliberate: the
// subtests run against one driver, and a buffer that is only read while a
// subtest is waiting fills with the runner's background activity and drops the
// record the next subtest is about to look for.
type eventTap struct {
	mu      sync.Mutex
	evs     []linuxEvent
	dropped int
	counts  map[string]int
	stop    chan struct{}
	done    chan struct{}
}

const eventTapCap = 1 << 17

func newEventTap(t *testing.T, buf *RingBuffer) *eventTap {
	tp := &eventTap{
		counts: map[string]int{},
		stop:   make(chan struct{}),
		done:   make(chan struct{}),
	}
	go func() {
		defer close(tp.done)
		for {
			select {
			case <-tp.stop:
				return
			default:
			}
			data, err := buf.TryRead()
			if err != nil || data == nil {
				time.Sleep(2 * time.Millisecond)
				continue
			}
			ev, ok := decodeLinuxEvent(data)
			if !ok {
				continue
			}
			tp.mu.Lock()
			if len(tp.evs) >= eventTapCap {
				half := eventTapCap / 2
				tp.evs = append(tp.evs[:0], tp.evs[half:]...)
				tp.dropped += half
			}
			tp.evs = append(tp.evs, ev)
			if ev.JSONType != "" {
				tp.counts["json:"+ev.JSONType]++
			} else {
				tp.counts[fmt.Sprintf("raw:%d", ev.RawType)]++
			}
			tp.mu.Unlock()
		}
	}()
	t.Cleanup(func() {
		close(tp.stop)
		<-tp.done
	})
	return tp
}

// mark returns a cursor into the event log. Events appended after it are the
// only ones a subtest considers, so one subtest's activity cannot satisfy
// another's assertion.
func (tp *eventTap) mark() int {
	tp.mu.Lock()
	defer tp.mu.Unlock()
	return tp.dropped + len(tp.evs)
}

// await polls for an event after mark that match accepts.
func (tp *eventTap) await(mark int, timeout time.Duration, match func(linuxEvent) bool) (linuxEvent, int, bool) {
	deadline := time.Now().Add(timeout)
	for {
		tp.mu.Lock()
		start := mark - tp.dropped
		if start < 0 {
			start = 0
		}
		window := tp.evs
		if start <= len(window) {
			window = window[start:]
		} else {
			window = nil
		}
		for _, ev := range window {
			if match(ev) {
				n := len(window)
				tp.mu.Unlock()
				return ev, n, true
			}
		}
		seen := len(window)
		tp.mu.Unlock()
		if time.Now().After(deadline) {
			return linuxEvent{}, seen, false
		}
		time.Sleep(10 * time.Millisecond)
	}
}

// summary describes everything the tap has seen, for a failure message.
func (tp *eventTap) summary() string {
	tp.mu.Lock()
	defer tp.mu.Unlock()
	keys := make([]string, 0, len(tp.counts))
	for k := range tp.counts {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	fmt.Fprintf(&b, "tap saw %d events (%d trimmed), by kind:", len(tp.evs)+tp.dropped, tp.dropped)
	for _, k := range keys {
		fmt.Fprintf(&b, " %s=%d", k, tp.counts[k])
	}
	return b.String()
}

// ------------------------------------------------------------ proof machinery

// linuxProof is what a per-category proof gets: a started driver, a tap on its
// ring buffer, and a temp directory of its own.
type linuxProof struct {
	drv *EBPFDriver
	tap *eventTap
	dir string
}

// tempPath returns a path under the subtest's own directory.
func (p *linuxProof) tempPath(name string) string {
	return filepath.Join(p.dir, name)
}

// listener binds a loopback TCP listener in the *test* process and accepts in
// the background. The test process's own events are dropped in the kernel by
// the self-filter, which is exactly what is wanted here: the listener is only
// a destination, and the assertion is about the helper that dials it.
func (p *linuxProof) listener(t *testing.T) string {
	t.Helper()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Skipf("MISSING PREREQUISITE: cannot bind a loopback TCP listener in this environment: %v", err)
	}
	t.Cleanup(func() { _ = ln.Close() })
	go func() {
		for {
			c, err := ln.Accept()
			if err != nil {
				return
			}
			go func() {
				_, _ = c.Read(make([]byte, 64))
				_ = c.Close()
			}()
		}
	}()
	return ln.Addr().String()
}

// expect waits for an event and fails with what did arrive when it does not.
func (p *linuxProof) expect(t *testing.T, mark int, what string, match func(linuxEvent) bool) linuxEvent {
	t.Helper()
	ev, seen, ok := p.tap.await(mark, 15*time.Second, match)
	if !ok {
		t.Fatalf("no %s arrived within 15s after generating the activity (%d events seen in this window).\n%s\nThe hook serving this category is attached, so the gap is in the in-kernel filter, the ringbuf submit, or the decode path.",
			what, seen, p.tap.summary())
	}
	t.Logf("%s: %s", what, ev)
	return ev
}

// observed returns the capability report's event count for cat.
func (p *linuxProof) observed(t *testing.T, cat CapabilityCategory) uint64 {
	t.Helper()
	return findCapability(t, p.drv.CapabilityReport(), cat).EventsObserved
}

// expectObserved waits for the capability report's own per-category counter to
// move.
//
// This is the assertion for categories whose events are indistinguishable on
// the ring buffer. Module load and module unload both decode to a
// type="module" envelope with no field saying which, so the only place the
// difference survives is the counter the report keeps -- which is also the
// number an operator reads, so asserting on it is not a weaker test, just a
// different one.
func (p *linuxProof) expectObserved(t *testing.T, cat CapabilityCategory, before uint64, what string) {
	t.Helper()
	deadline := time.Now().Add(15 * time.Second)
	for {
		now := p.observed(t, cat)
		if now > before {
			t.Logf("%s: capability report events_observed for %s rose %d -> %d", what, cat, before, now)
			return
		}
		if time.Now().After(deadline) {
			t.Fatalf("capability report events_observed for %q stayed at %d for 15s after %s.\n%s",
				cat, before, what, p.tap.summary())
		}
		time.Sleep(25 * time.Millisecond)
	}
}

