// linuxProof is what a per-category proof gets: a started driver, a tap on its
// ring buffer, and a temp directory of its own.
type linuxProof struct {
	drv *EBPFDriver
	tap *eventTap
	dir string
}

// kernelRelease is the running kernel's version string, or a note saying why
// it could not be read.
//
// Printed on every driver bring-up and in every failure message because this
// suite's "flakiness" turned out to be a mixed runner fleet: GitHub serves the
// ubuntu-24.04 image on more than one Azure kernel, and across seven
// consecutive runs of this lane every failure was on 7.0.0-1017-azure and
// every pass was on 6.17.0-1022-azure, with no exceptions either way. Nothing
// in the test output said which kernel it had run on, so a hard failure on one
// kernel read as an intermittent failure of the suite, and the subset of
// categories that failed varied only because it depends on which of a rare
// syscall's few calls happen to be missed.
//
// Any future "it fails about one run in three" should start by grouping the
// runs by this string.
func kernelRelease() string {
	raw, err := os.ReadFile("/proc/sys/kernel/osrelease")
	if err != nil {
		return "unknown (" + err.Error() + ")"
	}
	return strings.TrimSpace(string(raw))
}

// kernelTrace is the one-line kernel-side state of a category, for a log line
// after each failed attempt.
//
// Per attempt rather than only at the end, because the totals after six failed
// attempts cannot say whether the hook ran during any of them. With this, a
// failed attempt whose hook run count went up lost the record somewhere after
// the handler decided to emit it; one whose run count did not move never
// reached the handler at all. The flake this was written for turned out to be
// all-or-nothing per generated process, which is only visible per attempt.
func (p *linuxProof) kernelTrace(cat CapabilityCategory) string {
	loss := p.drv.KernelEventLossReport()
	sub, lost, ring := loss.kernelLossForCategory(cat)
	out := fmt.Sprintf("kernel: submitted=%d reserve_failed=%d on %s", sub, lost, ring)

	hooks := findCapabilityHooks(p.drv.CapabilityReport(), cat)
	if runs, counted := p.drv.ProgramRunTotalFor(hooks); counted {
		out += fmt.Sprintf("; hook invocations=%d", runs)
	} else {
		out += "; hook invocations=not measured"
	}
	if len(loss.FilterDrops) > 0 {
		out += fmt.Sprintf("; in-kernel filter drops=%v", loss.FilterDrops)
	}
	return out
}

// findCapabilityHooks returns the program names a category's row lists.
func findCapabilityHooks(rep CapabilityReport, cat CapabilityCategory) []string {
	for _, c := range rep.Categories {
		if c.Category == cat {
			return c.Attachments
		}
	}
	return nil
}

// tracepointEnableState reports what tracefs says about each of a category's
// attach targets.
//
// A tracepoint with an attached BPF program reads 1 in its "enable" file. If a
// program's run count is zero and its tracepoint reads 1, the hook is armed
// and the syscall under test is not reaching it; if it reads 0, the attach did
// not take effect however successfully the link call returned. Those are
// different bugs and the file is the cheapest way to tell them apart.
func tracepointEnableState(drv *EBPFDriver, hooks []string) string {
	targets := drv.AttachTargetsFor(hooks)
	if len(targets) == 0 {
		return ""
	}
	names := make([]string, 0, len(targets))
	for name := range targets {
		names = append(names, name)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("attach targets, and what tracefs says about them:")
	for _, name := range names {
		target := targets[name]
		fmt.Fprintf(&b, "\n    %s -> %s", name, target)
		group, tp, ok := strings.Cut(target, "/")
		if !ok {
			continue
		}
		for _, root := range []string{"/sys/kernel/tracing", "/sys/kernel/debug/tracing"} {
			path := filepath.Join(root, "events", group, tp, "enable")
			raw, err := os.ReadFile(path)
			if err != nil {
				continue
			}
			state := strings.TrimSpace(string(raw))
			fmt.Fprintf(&b, " (enable=%s", state)
			if state == "0" {
				b.WriteString(", so the kernel is not running anything on this tracepoint")
			}
			b.WriteString(")")
			break
		}
	}
	return b.String()
}

// diagnostics is what a failure needs in order to be attributable.
//
// Four numbers answer where an event went missing, and they are at four
// different points on the path. In kernel-to-userspace order:
//
//   - the in-kernel event_stats and filter_stats maps count, per event type,
//     the records a handler wrote, the records it threw away because the BPF
//     ring buffer was full, and the records a pid filter dropped before any
//     of that;
//   - the capability tracker counts events in processRecord, before any
//     policy gate or buffer write;
//   - DriverStats counts what the ring buffer readers handed up and what the
//     driver failed to decode;
//   - RingBufferStats counts what the userspace buffer refused for want of
//     space.
//
// The kernel-side pair is the one that was missing, and it is the one that
// decides the question. A category with nothing submitted, nothing lost and
// nothing filtered has a hook that did not run, however healthy the attach
// looked; a category with a non-zero reserve_failed has a hook that ran fine
// and a buffer that could not take the record. Those have different fixes and
// before these counters existed they produced identical output: zero
// everywhere, which reads exactly like an idle host.
func (p *linuxProof) diagnostics(cat CapabilityCategory) string {
	var b strings.Builder
	st := p.drv.Stats()
	fmt.Fprintf(&b, "kernel %s, %d CPUs\n", kernelRelease(), runtime.NumCPU())
	fmt.Fprintf(&b, "driver stats: received=%d processed=%d dropped=%d errors=%d uptime=%.1fs",
		st.EventsReceived, st.EventsProcessed, st.EventsDropped, st.ErrorCount, st.UptimeSeconds)
	if p.tap.buf != nil {
		rb := p.tap.buf.Stats()
		fmt.Fprintf(&b, "\nring buffer: produced=%d consumed=%d dropped=%d backlog=%.1f%%",
			rb.Produced, rb.Consumed, rb.Dropped, rb.BacklogPct)
	}
	fmt.Fprintf(&b, "\n%s", p.drv.KernelEventLossReport().Summary())
	for _, c := range p.drv.CapabilityReport().Categories {
		if c.Category != cat {
			continue
		}
		fmt.Fprintf(&b, "\ncapability row: %+v", c)
		// The hooks this row names, and whether the kernel is calling
		// them. "attached" is evidence the link call succeeded; a run
		// count is evidence the program executes; the tracepoint's own
		// enable file is evidence the kernel has it armed.
		if s := p.drv.ProgramRunCountsFor(c.Attachments); s != "" {
			fmt.Fprintf(&b, "\n%s", s)
		}
		if s := tracepointEnableState(p.drv, c.Attachments); s != "" {
			fmt.Fprintf(&b, "\n%s", s)
		}
	}
	return b.String()
}

// tempPath returns a path under the subtest's own directory.
func (p *linuxProof) tempPath(name string) string {
	return filepath.Join(p.dir, name)
}

// listener binds a loopback TCP listener in the *test* process and accepts in
// the background. The test process's own events are dropped in the kernel by
// the self-filter, which is exactly what is wanted here: the listener is only
// a destination, and the assertion is about the helper that dials it.
func (p *linuxProof) listener(t *testing.T) string {
	t.Helper()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Skipf("MISSING PREREQUISITE: cannot bind a loopback TCP listener in this environment: %v", err)
	}
	t.Cleanup(func() { _ = ln.Close() })
	go func() {
		for {
			c, err := ln.Accept()
			if err != nil {
				return
			}
			go func() {
				_, _ = c.Read(make([]byte, 64))
				_ = c.Close()
			}()
		}
	}()
	return ln.Addr().String()
}

// expect waits for an event and fails with what did arrive when it does not.
func (p *linuxProof) expect(t *testing.T, mark int, what string, match func(linuxEvent) bool) linuxEvent {
	t.Helper()
	ev, seen, ok := p.tap.await(mark, 15*time.Second, match)
	if !ok {
		t.Fatalf("no %s arrived within 15s after generating the activity (%d events seen in this window).\n%s\n%s\nThe hook serving this category is attached, so the gap is in the in-kernel filter, the ringbuf reserve, or the decode path -- and the kernel accounting above says which.",
			what, seen, p.tap.summary(), p.diagnostics(""))
	}
	t.Logf("%s: %s", what, ev)
	return ev
}

// proveWithRetry generates the activity and waits for the event, up to three
// times.
//
// One attempt is not enough on a shared runner. These hooks are global: the
// ring buffer carries every process's activity, the buffer can fill, and a
// record the kernel produced can be dropped in userspace before the tap sees
// it. Retrying the generation re-runs the whole path rather than waiting
// longer on a record that is already gone -- and if the hook is genuinely
// silent, three attempts fail just as surely as one, with the diagnostics
// below saying which of the three stages lost it.
func (p *linuxProof) proveWithRetry(t *testing.T, cat CapabilityCategory, what string,
	generate func() uint32, match func(linuxEvent, uint32) bool) linuxEvent {
	t.Helper()
	const attempts = 6
	worstSeen := 0
	for attempt := 1; attempt <= attempts; attempt++ {
		mark := p.tap.mark()
		pid := generate()
		ev, seen, ok := p.tap.await(mark, 4*time.Second, func(e linuxEvent) bool {
			return match(e, pid)
		})
		if ok {
			t.Logf("%s (attempt %d, pid %d): %s", what, attempt, pid, ev)
			return ev
		}
		worstSeen = seen
		t.Logf("attempt %d: no %s for pid %d within 4s (%d events seen; %s)",
			attempt, what, pid, seen, p.kernelTrace(cat))
	}
	t.Fatalf("no %s arrived in %d attempts (%d events seen in the last window).\n%s\n%s",
		what, attempts, worstSeen, p.tap.summary(), p.diagnostics(cat))
	return linuxEvent{}
}

// observed returns the capability report's event count for cat.
func (p *linuxProof) observed(t *testing.T, cat CapabilityCategory) uint64 {
	t.Helper()
	return findCapability(t, p.drv.CapabilityReport(), cat).EventsObserved
}

// expectObserved waits for the capability report's own per-category counter to
// move.
//
// This is the assertion for categories whose events are indistinguishable on
// the ring buffer. Module load and module unload both decode to a
// type="module" envelope with no field saying which, so the only place the
// difference survives is the counter the report keeps -- which is also the
// number an operator reads, so asserting on it is not a weaker test, just a
// different one.
func (p *linuxProof) expectObserved(t *testing.T, cat CapabilityCategory, before uint64, what string) {
	t.Helper()
	deadline := time.Now().Add(15 * time.Second)
	for {
		now := p.observed(t, cat)
		if now > before {
			t.Logf("%s: capability report events_observed for %s rose %d -> %d", what, cat, before, now)
			return
		}
		if time.Now().After(deadline) {
			// This is the assertion most in need of the kernel
			// counters: it fails on a number that stayed at zero,
			// and zero is what both a hook that never ran and a
			// ring buffer that refused every record look like.
			t.Fatalf("capability report events_observed for %q stayed at %d for 15s after %s.\n%s\n%s",
				cat, before, what, p.tap.summary(), p.diagnostics(cat))
		}
		time.Sleep(25 * time.Millisecond)
	}
}

