//go:build linux && integration

package kernel

// Linux end-to-end monitoring proof, one subtest per capability category.
//
// Everything else in this package tests the monitoring layer by inspecting it.
// These tests generate real kernel activity and assert the corresponding event
// comes out of the ring buffer, which is the only check that covers the whole
// path at once: object load, program attach, in-kernel filter, ringbuf submit,
// userspace read, decode, and the capability report's own accounting.
//
// Build-tagged `integration` because they need root and a compiled BPF object.
// Run with:
//
//	sudo -E go test -tags=integration ./internal/kernel/ -run TestLinuxMonitoring -v
//
// Prerequisite handling follows one rule: anything about the environment
// skips, with a message naming exactly what was missing and how to supply it;
// anything that happens after the driver starts successfully fails. A kernel
// that cannot load BPF is not a regression, and a driver that attaches and
// then produces no exec event is.
//
// One exception to that, deliberately: a verifier rejection is NOT treated as
// an environment limitation. It used to be, and the result was a green CI lane
// in which all four subtests skipped with "MISSING PREREQUISITE: eBPF driver
// failed to start" for months while the object had not loaded on any modern
// kernel. Set EDR_REQUIRE_EBPF=1 (CI does) and a failure to load or attach is
// a test failure.
//
// Note the self-filter interaction. installSelfFilter writes the agent's own
// PID into the per-subsystem pid_filter maps, so activity generated by this
// test process is dropped in the kernel and would never arrive. All activity
// is therefore generated in a child process, by re-executing the test binary
// in helper mode, and every assertion matches on that child's PID rather than
// on a name — a PID cannot be produced by unrelated background activity on the
// runner, and these runners are busy.

