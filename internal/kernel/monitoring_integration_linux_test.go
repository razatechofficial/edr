//go:build linux && integration

package kernel

// Linux end-to-end monitoring proof.
//
// Everything else in this package tests the monitoring layer by inspecting it.
// These tests generate real kernel activity and assert the corresponding event
// comes out of the ring buffer, which is the only check that covers the whole
// path at once: object load, program attach, in-kernel filter, ringbuf submit,
// userspace read, and decode.
//
// Build-tagged `integration` because they need root and a compiled BPF object.
// Run with:
//
//	sudo -E go test -tags=integration ./internal/kernel/ -run TestLinuxMonitoring -v
//
// Prerequisite handling follows one rule: anything about the environment
// skips, with a message naming exactly what was missing and how to supply it;
// anything that happens after the driver starts successfully fails. A kernel
// that cannot load BPF is not a regression, and a driver that attaches and
// then produces no exec event is.
//
// Note the self-filter interaction. installSelfFilter writes the agent's own
// PID into the per-subsystem pid_filter maps, so activity generated by this
// test process is dropped in the kernel and would never arrive. All activity
// is therefore generated in a child process, by re-executing the test binary
// in helper mode.

import (
	"context"
	"encoding/binary"
	"fmt"
	"net"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
	"time"
)

// helperEnvVar switches the test binary into helper mode. init() below runs
// the requested action and exits before the test framework starts, so the
// activity happens in a process whose PID the kernel is not filtering.
const (
	helperEnvVar   = "EDR_MONITORING_ITEST_HELPER"
	helperEnvArg   = "EDR_MONITORING_ITEST_ARG"
	helperActExec  = "exec"
	helperActWrite = "write"
	helperActDial  = "dial"
)

func init() {
	action := os.Getenv(helperEnvVar)
	if action == "" {
		return
	}
	arg := os.Getenv(helperEnvArg)
	if err := runHelperAction(action, arg); err != nil {
		fmt.Fprintf(os.Stderr, "helper %s failed: %v\n", action, err)
		os.Exit(1)
	}
	os.Exit(0)
}

func runHelperAction(action, arg string) error {
	switch action {
	case helperActExec:
		// Being executed at all is the event under test.
		return nil
	case helperActWrite:
		f, err := os.OpenFile(arg, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o600)
		if err != nil {
			return err
		}
		if _, err := f.WriteString("edr monitoring integration test\n"); err != nil {
			f.Close()
			return err
		}
		return f.Close()
	case helperActDial:
		c, err := net.DialTimeout("tcp", arg, 5*time.Second)
		if err != nil {
			return err
		}
		_, _ = c.Write([]byte("ping"))
		return c.Close()
	}
	return fmt.Errorf("unknown helper action %q", action)
}

// runHelper re-executes this test binary in helper mode and waits for it.
func runHelper(t *testing.T, action, arg string) {
	t.Helper()
	self, err := os.Executable()
	if err != nil {
		t.Fatalf("locating test binary for helper mode: %v", err)
	}
	cmd := exec.Command(self)
	cmd.Env = append(os.Environ(), helperEnvVar+"="+action, helperEnvArg+"="+arg)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("helper %s(%s) failed: %v\n%s", action, arg, err, out)
	}
}

// resolveBPFObjectForTest finds a compiled BPF object, preferring an explicit
// override so CI can point at the object make ebpf-link just produced.
func resolveBPFObjectForTest() (path string, tried []string) {
	if p := strings.TrimSpace(os.Getenv("EDR_BPF_OBJECT")); p != "" {
		tried = append(tried, p+" (from EDR_BPF_OBJECT)")
		if fileExists(p) {
			return p, tried
		}
	}
	candidates := []string{
		bpfObjectPathDefault,
		filepath.Join(EBPFSourceDir(), "edr.bpf.o"),
	}
	for _, p := range candidates {
		tried = append(tried, p)
		if fileExists(p) {
			return p, tried
		}
	}
	return "", tried
}

// startMonitoringForTest applies every environment gate in turn and returns a
// started driver plus its ring buffer. It skips, never fails.
func startMonitoringForTest(t *testing.T) (*EBPFDriver, *RingBuffer) {
	t.Helper()

	if euid := os.Geteuid(); euid != 0 {
		t.Skipf("MISSING PREREQUISITE: root. eBPF program loading needs CAP_BPF and CAP_PERFMON; this process has euid=%d. Re-run with: sudo -E go test -tags=integration ./internal/kernel/ -run %s", euid, t.Name())
	}

	objPath, tried := resolveBPFObjectForTest()
	if objPath == "" && len(bpfBytecode) == 0 {
		t.Skipf("MISSING PREREQUISITE: compiled BPF object. Tried: %s. Build one with `make ebpf ebpf-link`, then set EDR_BPF_OBJECT to platform/linux/ebpf/edr.bpf.o, or build the test with -tags embed_ebpf", strings.Join(tried, ", "))
	}

	if !fileExists("/sys/kernel/btf/vmlinux") {
		t.Skip("MISSING PREREQUISITE: kernel BTF at /sys/kernel/btf/vmlinux. The programs are CO-RE and need BTF; this kernel was built without CONFIG_DEBUG_INFO_BTF")
	}

	drv, err := NewEBPFDriver("monitoring-integration-test", objPath)
	if err != nil {
		t.Skipf("MISSING PREREQUISITE: eBPF driver could not be constructed: %v", err)
	}

	buf := NewRingBuffer(1 << 20)
	ctx, cancel := context.WithCancel(context.Background())

	if err := drv.Start(ctx, buf); err != nil {
		cancel()
		buf.Close()
		// A failure here is an environment limitation in practice:
		// locked-memory limits, a denied perf_event_open, a verifier
		// rejection on an unfamiliar kernel. Skip with the full
		// diagnostic rather than failing, and say where to look.
		t.Skipf("MISSING PREREQUISITE: eBPF driver failed to start on this kernel: %v\nLoader diagnostic: %s\nobject=%s", err, drv.LastLoadDiagnostics(), objPath)
	}

	t.Cleanup(func() {
		_ = drv.Stop()
		cancel()
		buf.Close()
	})

	attached := drv.AttachedProgramNames()
	if len(attached) == 0 {
		t.Fatalf("driver started but attached no programs; object=%s diagnostic=%s", objPath, drv.LastLoadDiagnostics())
	}
	t.Logf("driver started: %d programs attached", len(attached))
	return drv, buf
}

// requireAttachedProgram skips when the hook a subtest depends on is not
// attached in this build.
//
// This is the skip that keeps these tests honest about the loader's existing
// gaps: 23 of the 62 compiled programs never attach (see
// knownUnattachedPrograms), so a test asserting DNS or TCP-close telemetry
// would fail for a reason that has nothing to do with the kernel it is running
// on. Skipping names the program, so the message is actionable.
func requireAttachedProgram(t *testing.T, drv *EBPFDriver, prog string) {
	t.Helper()
	for _, p := range drv.AttachedProgramNames() {
		if p == prog {
			return
		}
	}
	reason := "it is not attached by this loader"
	if r, ok := ebpfUnattachableHooks[prog]; ok {
		reason = r
	}
	t.Skipf("MISSING PREREQUISITE: eBPF program %q is not attached, so this category cannot produce events: %s", prog, reason)
}

// rawEvent is a decoded ring buffer record. The layout is writeRawEvent's:
// type u16 @0, timestamp u64 @2, pid u32 @10, tid @14, uid @18, gid @22,
// payload from rawHeaderSize.
type rawEvent struct {
	Type    uint16
	PID     uint32
	Payload []byte
}

// firstString reads the leading length-prefixed string from the payload, which
// is how appendString encodes filenames and command lines.
func (e rawEvent) firstString() string {
	if len(e.Payload) < 2 {
		return ""
	}
	n := int(binary.LittleEndian.Uint16(e.Payload[0:2]))
	if n < 0 || 2+n > len(e.Payload) {
		return ""
	}
	return string(e.Payload[2 : 2+n])
}

// collectEvents drains buf until match returns true or the deadline passes.
// It returns the matching event and every event seen, so a failure can report
// what did arrive instead of only that the expected thing did not.
func collectEvents(t *testing.T, buf *RingBuffer, timeout time.Duration, match func(rawEvent) bool) (rawEvent, []rawEvent, bool) {
	t.Helper()
	deadline := time.Now().Add(timeout)
	var seen []rawEvent
	for time.Now().Before(deadline) {
		data, err := buf.TryRead()
		if err != nil || data == nil {
			time.Sleep(5 * time.Millisecond)
			continue
		}
		if len(data) < rawHeaderSize {
			// JSON envelopes (DNS, feature status) share the buffer
			// and are shorter or differently shaped; ignore them.
			continue
		}
		ev := rawEvent{
			Type:    binary.LittleEndian.Uint16(data[0:2]),
			PID:     binary.LittleEndian.Uint32(data[10:14]),
			Payload: data[rawHeaderSize:],
		}
		seen = append(seen, ev)
		if match(ev) {
			return ev, seen, true
		}
	}
	return rawEvent{}, seen, false
}

func summarizeSeen(seen []rawEvent) string {
	counts := make(map[uint16]int)
	for _, e := range seen {
		counts[e.Type]++
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%d events seen, by type:", len(seen))
	for typ, n := range counts {
		fmt.Fprintf(&b, " %d=%d", typ, n)
	}
	return b.String()
}

// TestLinuxMonitoringProcessExec execs a child and asserts the exec event
// surfaces.
func TestLinuxMonitoringProcessExec(t *testing.T) {
	drv, buf := startMonitoringForTest(t)
	requireAttachedProgram(t, drv, "tracepoint__syscalls__sys_enter_execve")

	self, err := os.Executable()
	if err != nil {
		t.Fatalf("locating test binary: %v", err)
	}
	wantName := filepath.Base(self)

	runHelper(t, helperActExec, "")

	ev, seen, ok := collectEvents(t, buf, 10*time.Second, func(e rawEvent) bool {
		return e.Type == bpfEvtProcExec && strings.Contains(e.firstString(), wantName)
	})
	if !ok {
		t.Fatalf("no exec event for %q arrived within 10s after execing it.\n%s\nThe execve tracepoint is attached, so either the ringbuf submit or the decode path is broken.", wantName, summarizeSeen(seen))
	}
	t.Logf("exec event: pid=%d filename=%q", ev.PID, ev.firstString())

	// The capability report must agree: this is the data the console shows,
	// so it has to reflect the same reality the ring buffer just did.
	rep := drv.CapabilityReport()
	exec := findCapability(t, rep, CapProcessExec)
	if !exec.Producing {
		t.Errorf("an exec event was observed on the ring buffer but CapabilityReport says process_exec is not producing: %+v", exec)
	}
}

// TestLinuxMonitoringFileWrite creates and writes a file in a child process
// and asserts a file event naming that path surfaces.
func TestLinuxMonitoringFileWrite(t *testing.T) {
	drv, buf := startMonitoringForTest(t)
	requireAttachedProgram(t, drv, "tracepoint__syscalls__sys_enter_openat")

	// Under the agent's own data directory prefix the kernel treats as
	// interesting is unnecessary here: path_filter is not consulted by any
	// program (see knownUnreadMaps), so every path is reported.
	path := filepath.Join(t.TempDir(), "edr-monitoring-itest.txt")

	runHelper(t, helperActWrite, path)

	base := filepath.Base(path)
	ev, seen, ok := collectEvents(t, buf, 10*time.Second, func(e rawEvent) bool {
		switch e.Type {
		case bpfEvtFileOpen, bpfEvtFileWrite:
			return strings.Contains(e.firstString(), base)
		}
		return false
	})
	if !ok {
		t.Fatalf("no file open/write event naming %q arrived within 10s after writing it.\n%s", base, summarizeSeen(seen))
	}
	t.Logf("file event: type=%d pid=%d filename=%q", ev.Type, ev.PID, ev.firstString())

	rep := drv.CapabilityReport()
	for _, cat := range []CapabilityCategory{CapFileOpen, CapFileWrite} {
		c := findCapability(t, rep, cat)
		if c.Producing {
			return
		}
	}
	t.Error("a file event was observed on the ring buffer but CapabilityReport says neither file_open nor file_write is producing")
}

// TestLinuxMonitoringOutboundTCPConnect dials a local listener from a child
// process and asserts the connect event surfaces.
func TestLinuxMonitoringOutboundTCPConnect(t *testing.T) {
	drv, buf := startMonitoringForTest(t)
	// The connect(2) tracepoint is the one that attaches. kp_tcp_v4_connect
	// would give richer socket-level detail and is never attached.
	requireAttachedProgram(t, drv, "tracepoint__syscalls__sys_enter_connect")

	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Skipf("MISSING PREREQUISITE: cannot bind a loopback TCP listener in this environment: %v", err)
	}
	defer ln.Close()
	go func() {
		c, err := ln.Accept()
		if err == nil {
			_ = c.Close()
		}
	}()

	runHelper(t, helperActDial, ln.Addr().String())

	ev, seen, ok := collectEvents(t, buf, 10*time.Second, func(e rawEvent) bool {
		return e.Type == bpfEvtNetConn
	})
	if !ok {
		t.Fatalf("no network connect event arrived within 10s after an outbound TCP connect to %s.\n%s", ln.Addr(), summarizeSeen(seen))
	}
	t.Logf("network connect event: pid=%d", ev.PID)

	rep := drv.CapabilityReport()
	conn := findCapability(t, rep, CapNetworkConnect)
	if !conn.Producing {
		t.Errorf("a connect event was observed on the ring buffer but CapabilityReport says network_connect is not producing: %+v", conn)
	}
}

// TestLinuxMonitoringCapabilityReportMatchesAttachments asserts the report an
// operator would read agrees with what the driver actually attached, on a real
// kernel. The static tests check the tables; this checks the live wiring.
func TestLinuxMonitoringCapabilityReportMatchesAttachments(t *testing.T) {
	drv, _ := startMonitoringForTest(t)

	attached := make(map[string]bool)
	for _, p := range drv.AttachedProgramNames() {
		attached[p] = true
	}

	rep := drv.CapabilityReport()
	if !rep.DriverRunning {
		t.Fatal("report says driver_running=false for a driver that started")
	}

	for _, c := range rep.Categories {
		for _, hook := range c.Attachments {
			if c.Attached && !attached[hook] {
				t.Errorf("category %q reports attachment %q, which is not in the driver's attach records", c.Category, hook)
			}
		}
		if c.Attached && len(c.Attachments) == 0 {
			t.Errorf("category %q is attached but names no attachment", c.Category)
		}
	}

	// The categories whose only hooks are unattachable must be reported
	// dark on a real kernel too, not quietly healthy.
	for _, cat := range []CapabilityCategory{CapNetworkDNS, CapTLSMetadata, CapScheduler} {
		c := findCapability(t, rep, cat)
		if c.Attached {
			t.Errorf("category %q reports attached on a live kernel, but every program serving it fails the loader's name checks; the report is overstating coverage", cat)
		}
	}

	t.Logf("capability summary on this kernel: %+v", rep.Summary)
}
