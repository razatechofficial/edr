// ---------------------------------------------------------------- helper mode

// helperEnvVar switches the test binary into helper mode. init() below runs
// the requested action and exits before the test framework starts, so the
// activity happens in a process whose PID the kernel is not filtering.
const (
	helperEnvVar = "EDR_MONITORING_ITEST_HELPER"
	helperEnvArg = "EDR_MONITORING_ITEST_ARG"

	helperActExec      = "exec"
	helperActFork      = "fork"
	helperActOpen      = "open"
	helperActWrite     = "write"
	helperActUnlink    = "unlink"
	helperActRename    = "rename"
	helperActChmod     = "chmod"
	helperActDial      = "dial"
	helperActListen    = "listen"
	helperActBind      = "bind"
	helperActDNS       = "dns"
	helperActSetID     = "setid"
	helperActCapset    = "capset"
	helperActPrctl     = "prctl"
	helperActUnshare   = "unshare"
	helperActPtrace    = "ptrace"
	helperActMadvise   = "madvise"
	helperActMount     = "mount"
	helperActModLoad   = "modload"
	helperActModUnload = "modunload"
	helperActTLS       = "tls"
)

func init() {
	action := os.Getenv(helperEnvVar)
	if action == "" {
		return
	}
	arg := os.Getenv(helperEnvArg)
	if err := runHelperAction(action, arg); err != nil {
		fmt.Fprintf(os.Stderr, "helper %s failed: %v\n", action, err)
		os.Exit(1)
	}
	os.Exit(0)
}

// helperRepeat is how many times a helper repeats a syscall it can repeat
// cheaply.
//
// One occurrence was not reliably observed. On a hosted runner a given
// syscall's event went missing often enough that about one category in five
// failed per run, with no drops recorded anywhere in userspace and
// events_observed at zero -- so the record never left the kernel. Twenty
// occurrences make that a non-event for the categories that can repeat, and
// for the ones that cannot (being exec'd, exiting) the retry loop in
// proveWithRetry does the same job across processes.
const helperRepeat = 20

// runHelperAction performs one kind of activity.
//
// Several actions deliberately make a syscall that cannot succeed:
// mount(NULL,...), finit_module(-1,...), delete_module on a name no module
// has, ptrace(PTRACE_ATTACH) against pid 0. The sys_enter_* tracepoints these
// categories hang off fire on syscall *entry*, before any of that is checked,
// so the event is produced while the runner's state is untouched. Generating
// real mounts and real module loads on a shared CI runner to prove a
// tracepoint fires would be a bad trade.
func runHelperAction(action, arg string) error {
	switch action {
	case helperActExec:
		// Being executed at all is the event under test.
		return nil

	case helperActFork:
		// fork/clone is observed in the *parent*, so the helper has to
		// be the one forking: a grandchild of the test process.
		self, err := os.Executable()
		if err != nil {
			return err
		}
		cmd := exec.Command(self)
		cmd.Env = append(os.Environ(), helperEnvVar+"="+helperActExec)
		return cmd.Run()

	case helperActOpen:
		for i := 0; i < helperRepeat; i++ {
			f, err := os.Open(arg)
			if err != nil {
				return err
			}
			_, _ = f.Read(make([]byte, 1))
			if err := f.Close(); err != nil {
				return err
			}
		}
		return nil

	case helperActWrite:
		f, err := os.OpenFile(arg, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o600)
		if err != nil {
			return err
		}
		for i := 0; i < helperRepeat; i++ {
			if _, err := f.WriteString("edr monitoring integration test\n"); err != nil {
				f.Close()
				return err
			}
		}
		return f.Close()

	case helperActUnlink:
		for i := 0; i < helperRepeat; i++ {
			if err := os.WriteFile(arg, []byte("delete me\n"), 0o600); err != nil {
				return err
			}
			if err := os.Remove(arg); err != nil {
				return err
			}
		}
		return nil

	case helperActRename:
		for i := 0; i < helperRepeat; i++ {
			if err := os.WriteFile(arg, []byte("rename me\n"), 0o600); err != nil {
				return err
			}
			if err := os.Rename(arg, arg+".renamed"); err != nil {
				return err
			}
		}
		return nil

	case helperActChmod:
		if err := os.WriteFile(arg, []byte("chmod me\n"), 0o600); err != nil {
			return err
		}
		for i := 0; i < helperRepeat; i++ {
			mode := os.FileMode(0o644)
			if i%2 == 1 {
				mode = 0o600
			}
			if err := os.Chmod(arg, mode); err != nil {
				return err
			}
		}
		return nil

	case helperActDial:
		for i := 0; i < helperRepeat; i++ {
			c, err := net.DialTimeout("tcp", arg, 5*time.Second)
			if err != nil {
				return err
			}
			_, _ = c.Write([]byte("ping"))
			if err := c.Close(); err != nil {
				return err
			}
		}
		return nil

	case helperActListen:
		// The accept hook runs in the context of the accepting task, so
		// the listener has to live here and the test dials it. The port
		// comes back on stdout.
		ln, err := net.Listen("tcp", "127.0.0.1:0")
		if err != nil {
			return err
		}
		fmt.Printf("PORT=%s\n", ln.Addr().String())
		os.Stdout.Sync()
		c, err := ln.Accept()
		if err != nil {
			ln.Close()
			return err
		}
		_ = c.Close()
		return ln.Close()

	case helperActBind:
		for i := 0; i < helperRepeat; i++ {
			c, err := net.ListenPacket("udp", "127.0.0.1:0")
			if err != nil {
				return err
			}
			if err := c.Close(); err != nil {
				return err
			}
		}
		return nil

	case helperActDNS:
		// A real query to a port-53 destination. tp_dns_sendto only
		// emits when the destination port is 53, so this cannot be
		// faked with an arbitrary port, and no responder is needed:
		// the event is produced on sendto entry.
		c, err := net.Dial("udp", arg)
		if err != nil {
			return err
		}
		defer c.Close()
		// Write errors are ignored on purpose: nothing is listening on
		// port 53, so the first datagram draws an ICMP port
		// unreachable and the next write fails with ECONNREFUSED. The
		// event this proves fires on sendto entry, before any of that.
		for i := 0; i < helperRepeat; i++ {
			_, _ = c.Write(dnsQueryWire("edr-monitoring-itest.example.com"))
		}
		return nil

	case helperActSetID:
		// Already root, so this is a no-op that still enters the
		// syscall. RawSyscall rather than syscall.Setresuid: the latter
		// is a Go runtime all-threads operation and we want exactly one
		// entry.
		for i := 0; i < helperRepeat; i++ {
			if _, _, e := unix.RawSyscall(unix.SYS_SETRESUID, 0, 0, 0); e != 0 {
				return fmt.Errorf("setresuid: %w", e)
			}
		}
		return nil

	case helperActCapset:
		// NULL header: EFAULT, after the tracepoint has fired.
		for i := 0; i < helperRepeat; i++ {
			unix.RawSyscall(unix.SYS_CAPSET, 0, 0, 0)
		}
		return nil

	case helperActPrctl:
		if _, _, e := unix.RawSyscall(unix.SYS_PRCTL, unix.PR_SET_NAME, 0, 0); e != 0 && e != unix.EFAULT {
			return fmt.Errorf("prctl: %w", e)
		}
		return nil

	case helperActUnshare:
		// CLONE_NEWUTS affects this process only and it exits
		// immediately, so nothing on the runner is disturbed.
		for i := 0; i < helperRepeat; i++ {
			if _, _, e := unix.RawSyscall(unix.SYS_UNSHARE, uintptr(unix.CLONE_NEWUTS), 0, 0); e != 0 {
				return fmt.Errorf("unshare: %w", e)
			}
		}
		return nil

	case helperActPtrace:
		// PTRACE_ATTACH against pid 0 fails with ESRCH; the entry
		// tracepoint has already fired.
		for i := 0; i < helperRepeat; i++ {
			unix.RawSyscall6(unix.SYS_PTRACE, uintptr(unix.PTRACE_ATTACH), 0, 0, 0, 0, 0)
		}
		return nil

	case helperActMadvise:
		b, err := unix.Mmap(-1, 0, 4096, unix.PROT_READ|unix.PROT_WRITE,
			unix.MAP_PRIVATE|unix.MAP_ANONYMOUS)
		if err != nil {
			return err
		}
		defer unix.Munmap(b)
		for i := 0; i < helperRepeat; i++ {
			if err := unix.Madvise(b, unix.MADV_NORMAL); err != nil {
				return err
			}
		}
		return nil

	case helperActMount:
		// All-NULL mount: EFAULT/EINVAL, nothing is mounted.
		for i := 0; i < helperRepeat; i++ {
			unix.RawSyscall6(unix.SYS_MOUNT, 0, 0, 0, 0, 0, 0)
		}
		return nil

	case helperActModLoad:
		// finit_module on a closed fd: EBADF, no module is loaded.
		empty, err := unix.BytePtrFromString("")
		if err != nil {
			return err
		}
		for i := 0; i < helperRepeat; i++ {
			unix.RawSyscall(unix.SYS_FINIT_MODULE,
				uintptr(^uintptr(0)), uintptr(unsafe.Pointer(empty)), 0)
		}
		return nil

	case helperActModUnload:
		name, err := unix.BytePtrFromString("edr_itest_absent_module")
		if err != nil {
			return err
		}
		for i := 0; i < helperRepeat; i++ {
			unix.RawSyscall(unix.SYS_DELETE_MODULE, uintptr(unsafe.Pointer(name)), 0, 0)
		}
		return nil

	case helperActTLS:
		// A TLS record header (0x16) whose handshake type is
		// ClientHello (0x01) is what kp_tls_tcp_sendmsg keys on. The
		// body does not have to be a valid ClientHello: the program
		// copies a bounded printable prefix and does not parse the
		// server_name extension.
		c, err := net.DialTimeout("tcp", arg, 5*time.Second)
		if err != nil {
			return err
		}
		defer c.Close()
		hello := []byte{0x16, 0x03, 0x01, 0x00, 0x30, 0x01}
		hello = append(hello, []byte("edr-monitoring-itest.example.com")...)
		// Write errors are ignored on purpose: the listener closes
		// after the first read, so later writes fail with EPIPE. The
		// kprobe fires on tcp_sendmsg entry, before that matters.
		for i := 0; i < helperRepeat; i++ {
			_, _ = c.Write(hello)
		}
		return nil
	}
	return fmt.Errorf("unknown helper action %q", action)
}

// dnsQueryWire builds a minimal DNS query packet for name.
func dnsQueryWire(name string) []byte {
	pkt := []byte{
		0x12, 0x34, // id
		0x01, 0x00, // standard query, recursion desired
		0x00, 0x01, // qdcount
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	}
	for _, label := range strings.Split(name, ".") {
		pkt = append(pkt, byte(len(label)))
		pkt = append(pkt, label...)
	}
	pkt = append(pkt, 0x00)       // root label
	pkt = append(pkt, 0x00, 0x01) // QTYPE A
	pkt = append(pkt, 0x00, 0x01) // QCLASS IN
	return pkt
}

// runHelper re-executes this test binary in helper mode, waits for it, and
// returns the PID the activity was generated under.
func runHelper(t *testing.T, action, arg string) uint32 {
	t.Helper()
	self, err := os.Executable()
	if err != nil {
		t.Fatalf("locating test binary for helper mode: %v", err)
	}
	cmd := exec.Command(self)
	cmd.Env = append(os.Environ(), helperEnvVar+"="+action, helperEnvArg+"="+arg)
	out, err := cmd.CombinedOutput()
	if cmd.Process == nil {
		t.Fatalf("helper %s(%s) never started: %v", action, arg, err)
	}
	pid := uint32(cmd.Process.Pid)
	if err != nil {
		t.Fatalf("helper %s(%s) [pid %d] failed: %v\n%s", action, arg, pid, err, out)
	}
	return pid
}

// startHelperListener starts the listen helper, reads the address it bound,
// and returns it with the helper's PID. The caller dials the address; the
// accept happens in the helper, which is the process the kernel is not
// filtering.
func startHelperListener(t *testing.T) (addr string, pid uint32, wait func()) {
	t.Helper()
	self, err := os.Executable()
	if err != nil {
		t.Fatalf("locating test binary for helper mode: %v", err)
	}
	cmd := exec.Command(self)
	cmd.Env = append(os.Environ(), helperEnvVar+"="+helperActListen)
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		t.Fatalf("helper stdout pipe: %v", err)
	}
	cmd.Stderr = os.Stderr
	if err := cmd.Start(); err != nil {
		t.Fatalf("starting listen helper: %v", err)
	}
	pid = uint32(cmd.Process.Pid)

	type res struct {
		line string
		err  error
	}
	ch := make(chan res, 1)
	go func() {
		line, err := bufio.NewReader(stdout).ReadString('\n')
		ch <- res{line, err}
	}()
	select {
	case r := <-ch:
		if r.err != nil {
			t.Fatalf("reading listen helper address: %v", r.err)
		}
		addr = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(r.line), "PORT="))
	case <-time.After(10 * time.Second):
		_ = cmd.Process.Kill()
		t.Fatal("listen helper did not report an address within 10s")
	}
	return addr, pid, func() { _ = cmd.Wait() }
}

