//go:build !windows

package kernel

import "testing"

// canonicalETWProviderGUIDs is the platform-independent ground truth that the
// Windows-side ETW driver must use. Tracked here so non-Windows CI lanes still
// catch accidental GUID regressions (e.g. typos in a refactor) even though the
// actual ETWDriver code is build-tagged Windows-only.
var canonicalETWProviderGUIDs = map[string][16]byte{
	"WMI-Activity": {
		0x04, 0xEF, 0x18, 0x14, // Data1 LE
		0xB4, 0xB0, // Data2 LE
		0x23, 0x46, // Data3 LE
		0xBF, 0x7E, 0xD7, 0x4A, 0xB4, 0x7B, 0xBD, 0xAA, // Data4
	},
	"PowerShell": {
		0x3B, 0x85, 0xC1, 0xA0,
		0x40, 0x5C,
		0x15, 0x4B,
		0x87, 0x66, 0x3C, 0xF1, 0xC5, 0x8F, 0x98, 0x5A,
	},
	"TaskScheduler": {
		0xEA, 0x24, 0x7B, 0xDE,
		0xC8, 0x73,
		0x09, 0x4A,
		0x98, 0x5D, 0x5B, 0xDA, 0xDC, 0xFA, 0x90, 0x17,
	},
	"BITS-Client": {
		0x5B, 0xC1, 0x1C, 0xEF,
		0xC1, 0x46,
		0x4E, 0x41,
		0xBB, 0x95, 0xE7, 0x6B, 0x07, 0x7B, 0xD5, 0x1E,
	},
	"Security-Auditing": {
		0x25, 0x96, 0x84, 0x54,
		0x78, 0x54,
		0x94, 0x49,
		0xA5, 0xBA, 0x3E, 0x3B, 0x03, 0x28, 0xC3, 0x0D,
	},
}

// TestCanonicalETWProviderGUIDsNonZero ensures every well-known GUID required
// by the Windows monitoring path is non-zero on every platform's CI lane.
func TestCanonicalETWProviderGUIDsNonZero(t *testing.T) {
	for name, g := range canonicalETWProviderGUIDs {
		zero := true
		for _, b := range g {
			if b != 0 {
				zero = false
				break
			}
		}
		if zero {
			t.Errorf("canonical GUID for %q is zero-value", name)
		}
	}
}
